def test_cloud_import_callback_refreshes_device_list_immediately(wizard_factory, monkeypatch):
    from mi_monitor_light_tray import device_list_wizard as module
    from mi_monitor_light_tray.token_extractor.types import XiaomiDeviceInfo

    wizard, path = wizard_factory(language="ru")
    cloud = {}
    def fake_cloud(parent, on_success, *, multi_select):
        cloud.update(parent=parent, callback=on_success, multi_select=multi_select)

    monkeypatch.setattr(module, "CloudLoginWindow", fake_cloud)
    # Device import must refresh from its completion callback, not a guessed
    # timeout that could fire before a slow QR sign-in has finished.
    monkeypatch.setattr(wizard._root, "after", Mock(side_effect=AssertionError("Unexpected timer")))
    wizard._open_cloud_login()
    assert cloud["multi_select"] is True
    assert cloud["parent"] is wizard._root
    assert wizard._config.devices == []
    for name, suffix in [("Desk lamp", "1"), ("Second lamp", "2")]:
        cloud["callback"](XiaomiDeviceInfo(
            name=name, did=suffix, token="a" * 32, localip=f"192.0.2.{suffix}",
            model="xiaomi.light.bar2",
        ))
        assert name in _texts(wizard._device_list_frame)
    assert [device.name for device in wizard._config.devices] == ["Desk lamp", "Second lamp"]
    assert len({device.id for device in wizard._config.devices}) == 2
    assert not path.exists()


def test_cloud_multi_select_imports_all_selected_devices_without_single_select_state(tk_root, monkeypatch):
    from mi_monitor_light_tray.cloud_login_window import CloudLoginWindow
    from mi_monitor_light_tray.token_extractor.types import XiaomiDeviceInfo

    monkeypatch.setattr(CloudLoginWindow, "_show_qrcode_login", lambda self: None)
    imported = []
    i18n.set_language("ru")
    window = CloudLoginWindow(tk_root, imported.append, multi_select=True)
    devices = [XiaomiDeviceInfo(
        name=f"Lamp {index}", did=str(index), token="a" * 32,
        localip=f"192.0.2.{index}", model="xiaomi.light.bar2",
    ) for index in (1, 2)]
    window._show_device_selection(devices)
    assert "Выбрать все" in _texts(window._root)
    assert "Подтвердить выбор" in _texts(window._root)
    assert not hasattr(window, "_selected_index")
    window._select_all()
    assert window._selected_indices == {0, 1}
    window._clear_selection()
    assert window._selected_indices == set()
    window._select_all()
    window._on_device_selected()
    assert imported == devices
    assert not window._root.winfo_exists()


@pytest.mark.parametrize("language, captions", [
    ("en", ["Yes", "No"]), ("ru", ["Да", "Нет"]), ("zh", ["是", "否"]),
])
@pytest.mark.parametrize("confirm", [False, True])
def test_modal_buttons_are_localized_and_enter_activates_focused_button(tk_root, language, captions, confirm):
    from mi_monitor_light_tray import dialogs

    i18n.set_language(language)
    errors = []
    observed = []

    def interact():
        window = next(child for child in tk_root.winfo_children() if isinstance(child, tk.Toplevel))
        try:
            buttons = [child for child in _descendants(window) if isinstance(child, ttk.Button)]
            observed.extend(str(button.cget("text")) for button in buttons)
            focused = buttons[0 if confirm else 1]
            focused.focus_force()
            window.update()
            assert window.focus_get() is focused
            # Send Return to the dialog with No focused. The dialog binding
            # must respect that focus instead of unconditionally answering Yes.
            window.event_generate("<Return>")
        except BaseException as exc:
            errors.append(exc)
        finally:
            if window.winfo_exists():
                window.destroy()

    # One callback enters the actual modal event loop; no polling or sleeps.
    tk_root.after(0, interact)
    result = dialogs.askyesno("Test", "Test message", parent=tk_root)
    assert not errors, errors
    assert observed == captions
    assert result is confirm


@pytest.mark.parametrize("language, is_on, reachable, error, expected_status", [
    ("ru", True, True, None, "Включена"),
    ("en", False, False, "Timed out", "Off (offline)"),
])
def test_flyout_rebuild_keeps_cached_state_and_updates_status_translation(
    tk_root, monkeypatch, language, is_on, reachable, error, expected_status,
):
    from mi_monitor_light_tray import flyout
    from mi_monitor_light_tray.miio_client import LightState

    monkeypatch.setattr(flyout.tk, "Tk", lambda: tk_root)
    light = SimpleNamespace(
        state=LightState(is_on=is_on, reachable=reachable, brightness=73, color_temp=5100, error=error),
        color_temp_min=2700, color_temp_max=6500,
        refresh=Mock(side_effect=AssertionError("No device refresh during translation")),
        set_power=Mock(side_effect=AssertionError("No power command during translation")),
        set_brightness=Mock(side_effect=AssertionError("No brightness command during translation")),
        set_color_temp=Mock(side_effect=AssertionError("No temperature command during translation")),
    )
    config = AppConfig(devices=[DeviceConfig(id="office", name="Office")])
    i18n.set_language("zh")
    window = flyout.FlyoutWindow({"office": light}, config, on_open_setup=Mock())
    window._apply_state(light.state, "office")
    previous_section = window._sections["office"]
    i18n.set_language(language)
    window.rebuild({"office": light}, config)
    section = window._sections["office"]
    assert section is not previous_section
    assert section._brightness_var.get() == 73
    assert section._color_temp_var.get() == 5100
    assert section._status_var.get() == expected_status
    assert i18n.t("亮度") in _texts(section.frame)
    assert i18n.t("色温") in _texts(section.frame)
    light.refresh.assert_not_called()
    light.set_power.assert_not_called()
    light.set_brightness.assert_not_called()
    light.set_color_temp.assert_not_called()
